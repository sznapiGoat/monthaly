  realizations
    .filter((r) => r !== item)
    .sort((a, b) => Number(b.category === item.category) - Number(a.category === item.category) || Math.abs(a.areaM2 - item.areaM2) - Math.abs(b.areaM2 - item.areaM2))
    .slice(0, count);
